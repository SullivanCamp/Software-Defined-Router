#!/usr/bin/env bash
#
# Builds a three-host test topology around the router.
#
#   ns h1  10.0.1.10/24 ---- veth ---- rt1 |
#   ns h2  10.0.2.10/24 ---- veth ---- rt2 |  sdrouter (root ns, no IPs)
#   ns h3  10.0.3.10/24 ---- veth ---- rt3 |
#
# The router-side ends deliberately carry no IP address, so the kernel stack
# ignores them entirely and every transit packet is handled by sdrouter through
# AF_PACKET. Because nothing answers ARP for the gateway addresses, each host
# gets a permanent static neighbor entry instead.
#
# Usage: sudo ./topology.sh up | down | conf <file>

set -euo pipefail

HOSTS=(1 2 3)
CONF_DEFAULT="/tmp/sdrouter-demo.conf"

need_root() {
    if [[ $EUID -ne 0 ]]; then
        echo "must run as root" >&2
        exit 1
    fi
}

down() {
    for i in "${HOSTS[@]}"; do
        ip netns del "h$i"        2>/dev/null || true
        ip link  del "rt$i"       2>/dev/null || true
    done
    echo "topology removed"
}

up() {
    down >/dev/null 2>&1 || true

    for i in "${HOSTS[@]}"; do
        ip netns add "h$i"
        ip link add "h${i}eth0" type veth peer name "rt$i"

        # Host side.
        ip link set "h${i}eth0" netns "h$i"
        ip netns exec "h$i" ip link set lo up
        ip netns exec "h$i" ip link set "h${i}eth0" up
        ip netns exec "h$i" ip addr add "10.0.$i.10/24" dev "h${i}eth0"
        ip netns exec "h$i" ip route add default via "10.0.$i.1"
        ip netns exec "h$i" sysctl -qw net.ipv6.conf.all.disable_ipv6=1 >/dev/null 2>&1 || true

        # Router side: up, no address, no IPv6 chatter.
        ip link set "rt$i" up
        sysctl -qw "net.ipv6.conf.rt$i.disable_ipv6=1" >/dev/null 2>&1 || true

        # The gateway 10.0.$i.1 is not owned by anyone, so pin its MAC.
        rmac=$(cat "/sys/class/net/rt$i/address")
        ip netns exec "h$i" ip neigh replace "10.0.$i.1" \
            lladdr "$rmac" dev "h${i}eth0" nud permanent
    done

    echo "topology up: h1/h2/h3 <-> rt1/rt2/rt3"
}

conf() {
    local out="${1:-$CONF_DEFAULT}"
    {
        echo "# generated by topology.sh - feed to sdrouter with -f"
        for i in "${HOSTS[@]}"; do
            echo "ADD_ROUTE 10.0.$i.0/24 rt$i"
        done
        echo
        for i in "${HOSTS[@]}"; do
            hmac=$(ip netns exec "h$i" cat "/sys/class/net/h${i}eth0/address")
            echo "ADD_NEIGH 10.0.$i.10 $hmac"
        done
    } > "$out"
    echo "wrote $out"
}

need_root
case "${1:-}" in
    up)   up ;;
    down) down ;;
    conf) conf "${2:-$CONF_DEFAULT}" ;;
    *)    echo "usage: $0 up|down|conf [file]" >&2; exit 1 ;;
esac
